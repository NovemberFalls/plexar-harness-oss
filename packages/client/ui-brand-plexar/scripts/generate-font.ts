#!/usr/bin/env node
/**
 * Regenerate `src/client/tokens/font.ts` from `src/client/tokens/fonts/montserrat-medium.woff2`.
 * The token CSS `@font-face` points at a relative `fonts/montserrat-medium.woff2`, which 404s
 * when the sheet is injected into the Host page (no such route there); the token installer
 * substitutes this base64 `data:` URL for that `url(...)` at injection time instead. Run this
 * script (`node --experimental-strip-types scripts/generate-font.ts` from the package root)
 * after re-copying the font from plexar-coord; it fails if the font file is missing.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const FONT_PATH = fileURLToPath(new URL('../src/client/tokens/fonts/montserrat-medium.woff2', import.meta.url))
const OUTPUT_PATH = fileURLToPath(new URL('../src/client/tokens/font.ts', import.meta.url))

const bytes = readFileSync(FONT_PATH)
const base64 = bytes.toString('base64')
const dataUrl = `data:font/woff2;base64,${base64}`

const source = `/**
 * Generated by scripts/generate-font.ts from tokens/fonts/montserrat-medium.woff2 — do not edit.
 * Re-run that script after re-copying the font to refresh this file.
 */
export const PLEXAR_TOKENS_FONT_DATA_URL = ${JSON.stringify(dataUrl)}
`

writeFileSync(OUTPUT_PATH, source)
